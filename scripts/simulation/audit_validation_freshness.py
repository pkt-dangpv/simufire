#!/usr/bin/env python3
"""Audit script: validation reports freshness and coherence.

Checks whether the validation suite scores can be trusted before relying on
them in code review or documentation.

Usage (from repo root):
    python scripts/simulation/audit_validation_freshness.py

Exit codes:
    0 — all critical checks passed (warnings may exist)
    1 — at least one CRITICAL issue found:
          - JSON parse error
          - report missing for a case that has a baseline
          - score mismatch between ESTADO_SESION and reference_checks.json
          - baseline.all_pass=False for a required case

Does NOT modify any file.  Read-only.
"""

from __future__ import annotations

import datetime
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

