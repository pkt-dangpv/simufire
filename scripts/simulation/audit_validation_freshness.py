BASELINES_DIR = ROOT / "sim" / "validation" / "baselines"
REPORTS_DIR = ROOT / "sim" / "validation" / "reports"
REF_CHECKS  = REPORTS_DIR / "reference_checks.json"
ESTADO_FILE = ROOT / "ESTADO_SESION_2026-05-21.md"

